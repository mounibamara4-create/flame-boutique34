"""Generates the wilaya and commune data used by the site and the database.

Sources (in data/):
  wilayas.json        the 69 wilayas: code, Arabic and French names, delivery zone (a helper for bulk
                      price entry only), and for wilayas 59-69 the wilaya they were created from.
  algeria_cities.json the 1541 communes with Arabic and French names, from
                      https://github.com/othmanus/algeria-cities (division into 58 wilayas).

The communes of wilayas 59-69 are not in that source. They stay under their former wilaya until the
owner moves them from the dashboard (Delivery tab), following the official gazette.

Outputs:
  src/locations.js        window.FB_LOCATIONS for the pages
  supabase/locations.sql  seed for the database (never overwrites communes already moved)

Run from the project folder:  python3 tools/gen_locations.py
"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
wilayas = json.loads((root / "data/wilayas.json").read_text(encoding="utf-8"))
cities = json.loads((root / "data/algeria_cities.json").read_text(encoding="utf-8"))

communes = sorted(([c["id"], int(c["wilaya_code"]), c["commune_name"].strip(), c["commune_name_ascii"].strip()] for c in cities),
                  key=lambda c: (c[1], c[3]))
assert len(communes) == 1541 and len({c[0] for c in communes}) == 1541
assert {c[1] for c in communes} <= {w["code"] for w in wilayas}

js = ("// Generated by tools/gen_locations.py from data/. Do not edit by hand.\n"
      "window.FB_LOCATIONS = {\n"
      "  wilayas: " + json.dumps([[w["code"], w["ar"], w["fr"], w["zone"], w["parent"]] for w in wilayas], ensure_ascii=False, separators=(",", ":")) + ",\n"
      "  // [id, wilaya code, Arabic name, French name]\n"
      "  communes: " + json.dumps(communes, ensure_ascii=False, separators=(",", ":")) + "\n};\n")
(root / "src/locations.js").write_text(js, encoding="utf-8")

q = lambda s: "'" + str(s).replace("'", "''") + "'"
sql = ["-- Generated by tools/gen_locations.py. Run after schema.sql. Safe to run again:",
       "-- names are refreshed, but a commune the owner moved to another wilaya stays where it was moved.",
       "insert into wilayas (code, name_ar, name_fr) values"]
sql.append(",\n".join(f"  ({w['code']}, {q(w['ar'])}, {q(w['fr'])})" for w in wilayas))
sql.append("on conflict (code) do update set name_ar = excluded.name_ar, name_fr = excluded.name_fr;")
for w in wilayas:
    if w["parent"]:
        sql.append(f"update wilayas set parent_code = {w['parent']} where code = {w['code']};")
sql.append("insert into communes (id, wilaya_code, name_ar, name_fr) values")
sql.append(",\n".join(f"  ({c[0]}, {c[1]}, {q(c[2])}, {q(c[3])})" for c in communes))
sql.append("on conflict (id) do update set name_ar = excluded.name_ar, name_fr = excluded.name_fr;")
(root / "supabase/locations.sql").write_text("\n".join(sql) + "\n", encoding="utf-8")
print("wilayas", len(wilayas), "communes", len(communes))
